// Generates src/icons.ts from manifest-data.mjs (STACK_ICONS/CERT_ICONS) and
// .glyphs.json (fetched by fetch-icons.mjs --only=glyphs). Run after any
// change to manifest-data.mjs or a re-fetch of glyphs, so the 108
// STACK/CERT entries and 46 glyph strings are never hand-transcribed.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { STACK_ICONS, CERT_ICONS } from './manifest-data.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '../..')
const glyphs = JSON.parse(readFileSync(path.join(__dirname, '.glyphs.json'), 'utf8'))

function quote(s) {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}
function stackEntries(obj) {
  return Object.entries(obj)
    .map(([key, def]) => `  ${quote(key)}: { files: [${def.files.map(quote).join(', ')}], kind: ${quote(def.kind)} },`)
    .join('\n')
}

const glyphNames = glyphs.map(([name]) => name)
const glyphType = glyphNames.map(quote).join(' | ')
const glyphEntries = glyphs.map(([name, , markup]) => `  ${quote(name)}: ${quote(markup)},`).join('\n')

const stackItemType = Object.keys(STACK_ICONS).map(quote).join(' | ')
const certIssuerType = Object.keys(CERT_ICONS).map(quote).join(' | ')

const out = `// GENERATED by tools/icons/build-manifest.mjs - do not hand-edit.
// Source data: tools/icons/manifest-data.mjs + tools/icons/.glyphs.json
// Provenance for every file: ICONS.md

export interface IconDef {
  files: string[]
  kind: 'brand' | 'concept'
}

// Exact item strings from STACK_GROUPS / issuer ids from CERTS in
// src/content.ts. Listed as a union (rather than only Record<string, ...>)
// so the 'satisfies' checks below fail to typecheck if an item is missing,
// misspelled, or renamed here without updating content.ts, or vice versa.
type StackItem = ${stackItemType}
type CertIssuer = ${certIssuerType}

const stackIcons = {
${stackEntries(STACK_ICONS)}
} satisfies Record<StackItem, IconDef>

const certIcons = {
${stackEntries(CERT_ICONS)}
} satisfies Record<CertIssuer, IconDef>

/** Key = the exact item string from STACK_GROUPS in src/content.ts. */
export const STACK_ICONS: Record<string, IconDef> = stackIcons

/** Key = issuer id from CERTS in src/content.ts. */
export const CERT_ICONS: Record<string, IconDef> = certIcons

/**
 * Inline Tabler Icons (MIT) outline glyphs for UI chrome (not the brand/tool
 * icon set above). 24x24 viewBox, fill="none" stroke="currentColor".
 */
export type GlyphName = ${glyphType}

export const GLYPHS: Record<GlyphName, string> = {
${glyphEntries}
}
`

writeFileSync(path.join(ROOT, 'src/icons.ts'), out)
console.log(`wrote src/icons.ts: ${Object.keys(STACK_ICONS).length} stack items, ${Object.keys(CERT_ICONS).length} cert issuers, ${glyphNames.length} glyphs`)
